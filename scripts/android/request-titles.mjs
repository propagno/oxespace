/**
 * The phone's request titles (C5 `RemoteAgentRow.request.titleCode`, DESIGN H1 on #347), from ONE catalog: the words
 * come from the desktop's main.json (`messages.<code>`), for the codes the allowlist names
 * (`REMOTE_REQUEST_TITLE_PARAMS` in shared/agents/remoteAgentRow.ts). They join the `mobile` strings under
 * `requestTitles.*`, and a generated Kotlin map gives the phone each code's string resource and argument order, so it
 * renders a code in its own language and falls back to the row's `title` for a code it does not know.
 */
import { resourceName } from './strings-xml.mjs'

export const REQUEST_TITLES_KOTLIN_PATH = 'mobile/android/app/src/main/java/com/oxespace/mobile/agents/RequestTitleStrings.kt'

const PLACEHOLDER = /\{\{\s*([\w.]+)\s*\}\}/g
const lookup = (catalog, path) => path.split('.').reduce((node, part) => node?.[part], catalog)

/** The `mobile` catalog plus `requestTitles.<code>` from main.json; throws when a code has no words or other placeholders. */
export function withRequestTitles(mobile, main, allowlist) {
  const titles = {}
  for (const [code, keys] of Object.entries(allowlist)) {
    const text = lookup(main, `messages.${code}`)
    if (typeof text !== 'string') throw new Error(`[android] main:messages.${code} has no words for the phone`)
    const used = [...new Set([...text.matchAll(PLACEHOLDER)].map(match => match[1]))].sort()
    if (used.join() !== [...keys].sort().join()) throw new Error(`[android] main:messages.${code} uses {{${used.join('}}, {{')}}} but the allowlist names ${keys.length ? keys.join(', ') : 'none'}`)
    let node = titles
    const parts = code.split('.')
    for (const part of parts.slice(0, -1)) node = node[part] ??= {}
    node[parts.at(-1)] = text
  }
  return { ...mobile, requestTitles: titles }
}

/** Kotlin: code → string resource and the order its arguments go in (the English text's), for the allowed codes. */
export function requestTitlesKotlin(english, allowlist) {
  const entries = Object.entries(allowlist).map(([code, keys]) => {
    const text = lookup(english, `messages.${code}`)
    const order = [...new Set([...String(text).matchAll(PLACEHOLDER)].map(match => match[1]))].filter(name => keys.includes(name))
    return `        "${code}" to RequestTitleString(R.string.${resourceName(`requestTitles.${code}`)}, listOf(${order.map(name => `"${name}"`).join(', ')})),`
  })
  return [
    '// Generated by scripts/android/generate.mjs from shared/locales/*/main.json and the C5 allowlist of request title',
    '// codes. Do not edit: a change goes through a CCR, then `npm run android:generate`.',
    '',
    'package com.oxespace.mobile.agents',
    '',
    'import com.oxespace.mobile.R',
    '',
    '/** One request title the phone renders itself: its string and the `titleParams` keys, in argument order. */',
    'data class RequestTitleString(val res: Int, val params: List<String>)',
    '',
    '/**',
    ' * `RemoteAgentRow.request.titleCode` → the phone\'s own string. A code missing here (a newer desktop) renders the',
    ' * row\'s `title` words instead.',
    ' */',
    'object RequestTitleStrings {',
    '    val byCode: Map<String, RequestTitleString> = mapOf(',
    ...entries,
    '    )',
    '}',
    ''
  ].join('\n')
}
