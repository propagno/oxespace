/**
 * Kotlin design tokens for the Android app from the desktop's Mandacaru tokens (src/design/tokens, C4): every color
 * role in light and dark, spacing, radius, type sizes, weights, leading and motion. The app maps them onto Material 3
 * in OxeTheme.kt. When C4 exports tokens.json, this reads it instead of the modules.
 */
export const THEME_KOTLIN_PATH = 'mobile/android/app/src/main/java/com/oxespace/mobile/ui/theme/OxeTokens.kt'

const HEADER = `// Generated by scripts/android/generate.mjs from src/design/tokens (C4). Do not edit: change the token on the
// desktop, then \`npm run android:generate\`.`

/** `intent-success-bg-hover` → intentSuccessBgHover, `2xs` → text2xs with a prefix. */
export function camelName(name, prefix = '') {
  const parts = String(name).split('-').filter(Boolean)
  const joined = parts.map((part, index) => index === 0 && !prefix ? part : part.charAt(0).toUpperCase() + part.slice(1)).join('')
  return prefix ? `${prefix}${joined}` : joined
}

/** `#1f6b4a` → Color(0xFF1F6B4A); `rgba(18, 28, 22, 0.32)` → Color(0x52121C16). */
export function kotlinColor(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value)
  if (hex) return `Color(0xFF${hex[1].toUpperCase()})`
  const rgba = /^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/.exec(value)
  if (rgba) {
    const byte = number => Math.round(number).toString(16).padStart(2, '0').toUpperCase()
    return `Color(0x${byte(Number(rgba[4]) * 255)}${byte(Number(rgba[1]))}${byte(Number(rgba[2]))}${byte(Number(rgba[3]))})`
  }
  throw new Error(`[android] no Kotlin color for \`${value}\`; extend scripts/android/theme-kotlin.mjs`)
}

function milliseconds(value) {
  const match = /^([\d.]+)(ms|s)$/.exec(value)
  if (!match) throw new Error(`[android] no duration for \`${value}\``)
  return Math.round(Number(match[1]) * (match[2] === 's' ? 1000 : 1))
}

function easing(value) {
  if (value === 'linear') return 'LinearEasing'
  const match = /^cubic-bezier\(([^)]+)\)$/.exec(value)
  if (!match) throw new Error(`[android] no easing for \`${value}\``)
  return `CubicBezierEasing(${match[1].split(',').map(part => `${Number(part.trim())}f`).join(', ')})`
}

const dp = value => {
  const match = /^(\d+)px$/.exec(String(value))
  if (!match) throw new Error(`[android] no dp for \`${value}\``)
  return `${match[1]}.dp`
}

/**
 * @param {{ colorRoles: (mode: 'light' | 'dark') => Record<string, string>, IDENTITY: { provider: Record<string, string>, avatar: readonly string[] }, SPACE: Record<string, string>, RADIUS: Record<string, string>, TEXT: Record<string, number>, WEIGHT: Record<string, number>, LEADING: Record<string, number>, MOTION: Record<string, string>, REDUCED_MOTION: Record<string, string> }} tokens
 */
export function themeKotlin(tokens) {
  const light = tokens.colorRoles('light')
  const dark = tokens.colorRoles('dark')
  const roles = Object.keys(light)
  const missing = roles.filter(role => !(role in dark)).concat(Object.keys(dark).filter(role => !(role in light)))
  if (missing.length) throw new Error(`[android] color roles differ between modes: ${missing.join(', ')}`)

  const out = [HEADER, '', 'package com.oxespace.mobile.ui.theme', '']
  out.push(
    'import androidx.compose.animation.core.CubicBezierEasing',
    'import androidx.compose.animation.core.Easing',
    'import androidx.compose.animation.core.LinearEasing',
    'import androidx.compose.runtime.Immutable',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    ''
  )

  out.push('/** Every semantic color role of the desktop, by the same name in camel case. */', '@Immutable', 'class OxeColors(')
  out.push(...roles.map(role => `    val ${camelName(role)}: Color,`), ')', '')
  for (const [name, values] of [['LightOxeColors', light], ['DarkOxeColors', dark]]) {
    out.push(`val ${name} = OxeColors(`, ...roles.map(role => `    ${camelName(role)} = ${kotlinColor(values[role])},`), ')', '')
  }

  out.push('/** Colors that mean the same in both modes: providers and avatars. */', 'object OxeIdentity {')
  for (const [name, value] of Object.entries(tokens.IDENTITY.provider)) out.push(`    val ${camelName(name, 'provider')} = ${kotlinColor(value)}`)
  out.push(`    val avatars = listOf(${tokens.IDENTITY.avatar.map(kotlinColor).join(', ')})`, '}', '')

  out.push('/** Spacing in 4 dp steps. */', 'object OxeSpace {')
  for (const [name, value] of Object.entries(tokens.SPACE)) out.push(`    val space${name} = ${dp(value)}`)
  out.push('}', '')

  out.push('object OxeRadius {')
  for (const [name, value] of Object.entries(tokens.RADIUS)) out.push(`    val ${camelName(name)} = ${dp(value)}`)
  out.push('}', '')

  out.push('/** Type sizes, weights and leading of the desktop scale. */', 'object OxeType {')
  for (const [name, value] of Object.entries(tokens.TEXT)) out.push(`    val ${camelName(name, 'text')} = ${value}.sp`)
  for (const [name, value] of Object.entries(tokens.WEIGHT)) out.push(`    val ${camelName(name, 'weight')} = FontWeight(${value})`)
  for (const [name, value] of Object.entries(tokens.LEADING)) out.push(`    const val ${camelName(name, 'leading')} = ${value}f`)
  out.push('}', '')

  const durations = Object.entries(tokens.MOTION).filter(([name]) => name.startsWith('duration-'))
  const easings = Object.entries(tokens.MOTION).filter(([name]) => name.startsWith('ease-'))
  out.push(
    '/**',
    ' * Motion in milliseconds. With reduced motion (animator scale 0 or the accessibility setting) transitions become',
    ' * instant and the spinner turns slowly, as on the desktop.',
    ' */',
    '@Immutable',
    'class OxeMotion(',
    ...durations.map(([name]) => `    val ${camelName(name)}: Int,`),
    ') {',
    '    companion object {'
  )
  for (const [name, easingValue] of easings) out.push(`        val ${camelName(name)}: Easing = ${easing(easingValue)}`)
  out.push('    }', '}', '')
  for (const [name, overrides] of [['StandardOxeMotion', {}], ['ReducedOxeMotion', tokens.REDUCED_MOTION]]) {
    out.push(`val ${name} = OxeMotion(`, ...durations.map(([key, value]) => `    ${camelName(key)} = ${milliseconds(overrides[key] ?? value)},`), ')', '')
  }
  return `${out.join('\n').trimEnd()}\n`
}
