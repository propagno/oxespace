/**
 * Android string resources from the `mobile` translation catalogs (shared/locales/<language>/mobile.json), so the app
 * is translated the same way as the desktop and tests/i18n-catalog.test.ts keeps both languages aligned.
 *
 * `home.title` becomes `home_title`; `{{name}}` becomes a positional argument numbered by its first appearance in
 * English, so every language passes the same arguments; keys ending in `_one`, `_other`… become one `<plurals>`.
 */
export const STRINGS_XML_PATHS = {
  en: 'mobile/android/app/src/main/res/values/strings.xml',
  'pt-BR': 'mobile/android/app/src/main/res/values-pt-rBR/strings.xml'
}

const PLURAL = /_(zero|one|two|few|many|other)$/
const PLACEHOLDER = /\{\{\s*([\w.]+)\s*\}\}/g

function flatten(catalog, prefix = '') {
  const out = new Map()
  for (const [key, value] of Object.entries(catalog)) {
    const path = prefix ? `${prefix}.${key}` : key
    if (value && typeof value === 'object') for (const [inner, text] of flatten(value, path)) out.set(inner, text)
    else out.set(path, String(value))
  }
  return out
}

export const resourceName = key => key.replace(/[.\-]/g, '_').replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase()

/** Escapes for aapt: XML entities, then quotes, apostrophes, a leading @ or ?, and new lines. */
function escape(text, formatted) {
  let out = text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  out = out.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/'/g, "\\'").replace(/\n/g, '\\n')
  if (formatted) out = out.replace(/%/g, '%%')
  return out.replace(/^([@?])/, '\\$1')
}

/** Argument numbers by placeholder name, in the order the English text first uses them. */
function argumentOrder(englishForms) {
  const order = new Map()
  for (const text of englishForms) for (const [, name] of text.matchAll(PLACEHOLDER)) if (name !== 'count' && !order.has(name)) order.set(name, order.size + 1)
  return order
}

function render(text, order, key, plural) {
  const formatted = PLACEHOLDER.test(text) || plural
  PLACEHOLDER.lastIndex = 0
  const escaped = escape(text, formatted)
  return escaped.replace(PLACEHOLDER, (_, name) => {
    // The count goes last, after the named arguments, so callers pass (…named, count) and the quantity.
    if (plural && name === 'count') return `%${order.size + 1}$d`
    if (!order.has(name)) throw new Error(`[android] mobile:${key} uses {{${name}}}, which the English text doesn't have`)
    return `%${order.get(name)}$s`
  })
}

/**
 * @param {Record<string, unknown>} english the en catalog
 * @param {Record<string, unknown>} catalog the catalog to render (English itself for values/)
 * @param {string} language
 */
export function stringsXml(english, catalog, language) {
  const source = flatten(english)
  const entries = flatten(catalog)
  const groups = new Map()
  for (const [key, text] of entries) {
    const base = key.replace(PLURAL, '')
    const quantity = PLURAL.exec(key)?.[1]
    const group = groups.get(base) ?? { forms: new Map(), plural: false }
    group.forms.set(quantity ?? '', text)
    group.plural ||= Boolean(quantity)
    groups.set(base, group)
  }
  const names = new Map()
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- Generated by scripts/android/generate.mjs from shared/locales/${language}/mobile.json. Do not edit: change the`,
    '     catalog, then `npm run android:generate`. -->',
    '<resources>'
  ]
  for (const [key, group] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const name = resourceName(key)
    if (names.has(name)) throw new Error(`[android] mobile:${key} and mobile:${names.get(name)} both become ${name}`)
    names.set(name, key)
    const englishForms = [...source].filter(([sourceKey]) => sourceKey.replace(PLURAL, '') === key).map(([, text]) => text)
    const order = argumentOrder(englishForms)
    if (group.plural) {
      lines.push(`    <plurals name="${name}">`)
      for (const [quantity, text] of group.forms) lines.push(`        <item quantity="${quantity}">${render(text, order, key, true)}</item>`)
      lines.push('    </plurals>')
    } else {
      lines.push(`    <string name="${name}">${render(group.forms.get(''), order, key, false)}</string>`)
    }
  }
  lines.push('</resources>')
  return `${lines.join('\n')}\n`
}
