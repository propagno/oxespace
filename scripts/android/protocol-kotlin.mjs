/**
 * Kotlin for the Android app from the C5 contract (shared/remote/protocol.ts): the version, the limits, one enum per
 * `typeof LIST[number]` alias, the other lists as sets, and every frame as a kotlinx.serialization class under the
 * sealed `RemoteFrame`. Values come from the module itself; shapes and comments from its syntax tree.
 * A type the mapping doesn't know fails the generation, so a contract change can't silently lose a field.
 */
import ts from 'typescript'

export const PROTOCOL_KOTLIN_PATH = 'mobile/android/protocol/src/main/kotlin/com/oxespace/mobile/protocol/RemoteProtocol.kt'

const HEADER = `// Generated by scripts/android/generate.mjs from shared/remote/protocol.ts (C5). Do not edit: a change to the
// contract goes through a CCR to the coordinator, then \`npm run android:generate\`.`

/** `thread.respondRequest` → THREAD_RESPOND_REQUEST, `too-many-subscriptions` → TOO_MANY_SUBSCRIPTIONS. */
export function constantName(wire) {
  return wire.split(/[.\-_]/).flatMap(part => part.split(/(?=[A-Z])/)).filter(Boolean).map(part => part.toUpperCase()).join('_')
}

const capitalize = text => text.charAt(0).toUpperCase() + text.slice(1)

function kdoc(node, source, indent) {
  const ranges = ts.getLeadingCommentRanges(source, node.pos) ?? []
  const docs = ranges.map(range => source.slice(range.pos, range.end)).filter(text => text.startsWith('/**'))
  if (docs.length === 0) return ''
  const lines = docs[docs.length - 1]
    .replace(/^\/\*\* ?/, '').replace(/\*\/$/, '')
    .split('\n').map(line => line.replace(/^\s*\* ?/, '').trimEnd())
  while (lines.length && !lines[0].trim()) lines.shift()
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop()
  // Kotlin nests block comments, so an opener inside the text would swallow the rest of the file.
  const body = lines.map(line => line.replaceAll('/*', '/ *'))
  if (body.length === 1) return `${indent}/** ${body[0]} */\n`
  return `${indent}/**\n${body.map(line => `${indent} *${line ? ` ${line}` : ''}`).join('\n')}\n${indent} */\n`
}

function readDeclarations(source) {
  const file = ts.createSourceFile('protocol.ts', source, ts.ScriptTarget.ES2022, true)
  const consts = new Map()
  const listAliases = new Map()
  const interfaces = []
  for (const statement of file.statements) {
    if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) consts.set(declaration.name.getText(file), { statement, declaration })
    } else if (ts.isTypeAliasDeclaration(statement) && ts.isIndexedAccessTypeNode(statement.type) && ts.isTypeQueryNode(statement.type.objectType)) {
      listAliases.set(statement.name.text, statement.type.objectType.exprName.getText(file))
    } else if (ts.isInterfaceDeclaration(statement)) {
      interfaces.push(statement)
    }
  }
  return { file, consts, listAliases, interfaces }
}

/** The frame type an interface carries through `extends FrameBase<'…'>`, or null for helper interfaces. */
function frameTag(declaration) {
  for (const clause of declaration.heritageClauses ?? []) {
    for (const type of clause.types) {
      const argument = type.typeArguments?.[0]
      if (type.expression.getText() === 'FrameBase' && argument && ts.isLiteralTypeNode(argument) && ts.isStringLiteral(argument.literal)) return argument.literal.text
    }
  }
  return null
}

function kotlinType(node, context, nested) {
  if (node.kind === ts.SyntaxKind.StringKeyword) return 'String'
  if (node.kind === ts.SyntaxKind.NumberKeyword) return 'Long'
  if (node.kind === ts.SyntaxKind.BooleanKeyword) return 'Boolean'
  if (node.kind === ts.SyntaxKind.UnknownKeyword) return 'JsonElement'
  if (ts.isArrayTypeNode(node)) return `List<${kotlinType(node.elementType, context, nested)}>`
  if (ts.isTypeReferenceNode(node)) {
    const name = node.typeName.getText()
    const args = node.typeArguments?.map(arg => arg.getText()) ?? []
    if (name === 'Record' && args[0] === 'string' && args[1] === 'unknown') return 'JsonObject'
    if (context.enums.has(name) && args.length === 0) return name
  }
  if (ts.isTypeLiteralNode(node) && nested) return nested(node)
  throw new Error(`[android] no Kotlin mapping for \`${node.getText()}\` in ${context.where}; extend scripts/android/protocol-kotlin.mjs`)
}

function properties(members, context, indent) {
  const nestedClasses = []
  const lines = members.map(member => {
    if (!ts.isPropertySignature(member) || !member.type) throw new Error(`[android] unsupported member \`${member.getText()}\` in ${context.where}`)
    const name = member.name.getText()
    const optional = Boolean(member.questionToken)
    const type = kotlinType(member.type, { ...context, where: `${context.where}.${name}` }, literal => {
      const className = capitalize(name)
      nestedClasses.push(dataClass(className, literal.members, null, { ...context, where: `${context.where}.${name}` }, `${indent}`, ''))
      return className
    })
    return `${kdoc(member, context.source, indent)}${indent}val ${name}: ${type}${optional ? '? = null' : ''},`
  })
  return { lines, nestedClasses }
}

function dataClass(name, members, tag, context, indent, supertype) {
  const { lines, nestedClasses } = properties(members, context, `${indent}    `)
  const annotations = [`${indent}@Serializable`, ...(tag ? [`${indent}@SerialName("${tag}")`] : [])].join('\n')
  const body = nestedClasses.length ? ` {\n${nestedClasses.join('\n')}${indent}}` : ''
  return `${annotations}\n${indent}data class ${name}(\n${lines.join('\n')}\n${indent})${supertype}${body}\n`
}

/**
 * @param {string} source text of shared/remote/protocol.ts
 * @param {Record<string, unknown>} values the same module, imported
 */
export function protocolKotlin(text, values) {
  const source = text.replace(/\r\n/g, '\n')
  const { consts, listAliases, interfaces } = readDeclarations(source)
  const enums = new Map([...listAliases].filter(([alias]) => alias !== 'RemoteForbidden'))
  const context = { source, enums, where: 'protocol.ts' }
  const out = [HEADER, '', 'package com.oxespace.mobile.protocol', '']
  out.push('import kotlinx.serialization.SerialName', 'import kotlinx.serialization.Serializable', 'import kotlinx.serialization.json.JsonElement', 'import kotlinx.serialization.json.JsonObject', '')

  const preamble = kdoc(consts.get('REMOTE_PROTOCOL_VERSION').statement, source, '').replace(/^\/\*\*/, '/*').replace(/\*\/\n$/, '*/\n')
  out.push(preamble)
  out.push(`const val REMOTE_PROTOCOL_VERSION: Int = ${values.REMOTE_PROTOCOL_VERSION}`, '')

  const limits = consts.get('REMOTE_LIMITS')
  out.push(`${kdoc(limits.statement, source, '')}object RemoteLimits {`)
  const literal = limits.declaration.initializer.expression ?? limits.declaration.initializer
  for (const property of literal.properties) {
    const key = property.name.getText()
    const value = values.REMOTE_LIMITS[key]
    if (!Number.isInteger(value)) throw new Error(`[android] REMOTE_LIMITS.${key} is not an integer`)
    out.push(`${kdoc(property, source, '    ')}    const val ${constantName(key)}: ${key.endsWith('Ms') ? 'Long' : 'Int'} = ${value}${key.endsWith('Ms') ? 'L' : ''}`)
  }
  out.push('}', '')

  for (const [alias, listName] of enums) {
    const { statement } = consts.get(listName)
    const entries = values[listName].map(wire => `    @SerialName("${wire}") ${constantName(wire)}("${wire}"),`)
    out.push(`${kdoc(statement, source, '')}@Serializable\nenum class ${alias}(val wire: String) {`, ...entries, '    ;', '', '    companion object {', `        fun fromWire(wire: String): ${alias}? = entries.firstOrNull { it.wire == wire }`, '    }', '}', '')
  }

  for (const [name, { statement, declaration }] of consts) {
    if (!Array.isArray(values[name]) || [...enums.values()].includes(name)) continue
    const satisfies = declaration.initializer && ts.isSatisfiesExpression(declaration.initializer) ? declaration.initializer.type : null
    const element = satisfies && ts.isTypeOperatorNode(satisfies) && ts.isArrayTypeNode(satisfies.type) ? satisfies.type.elementType.getText() : null
    if (element && enums.has(element)) {
      const items = values[name].map(wire => `    ${element}.${constantName(wire)},`)
      out.push(`${kdoc(statement, source, '')}val ${name}: Set<${element}> = setOf(`, ...items, ')', '')
    } else {
      out.push(`${kdoc(statement, source, '')}val ${name}: Set<String> = setOf(`, ...values[name].map(wire => `    "${wire}",`), ')', '')
    }
  }

  out.push('/** Every frame; the JSON `type` field picks the class. */', '@Serializable', 'sealed interface RemoteFrame', '')
  for (const declaration of interfaces) {
    const tag = frameTag(declaration)
    if (!tag) continue
    const name = declaration.name.text
    out.push(kdoc(declaration, source, '') + dataClass(name, declaration.members, tag, { ...context, where: name }, '', ' : RemoteFrame'))
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}
