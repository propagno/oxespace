const AFTER = { pseudo: '::after' }

/** The grab area across the line: the ::after's own width (or height), else the element plus the ::after's outsets. */
function grab(node: Element, axis: 'x' | 'y'): number {
  const size = px(css(node, axis === 'x' ? ['width', 'inline-size'] : ['height', 'block-size']))
  const own = px(css(node, axis === 'x' ? ['width', 'inline-size'] : ['height', 'block-size'], AFTER))
  if (Number.isFinite(own) && own > 0) return own
  const inset = css(node, 'inset', AFTER)
  const parts = inset ? inset.split(/\s+(?![^(]*\))/) : []
  const sides = parts.length === 0 ? [] : parts.length === 1 ? [parts[0], parts[0], parts[0], parts[0]] : parts.length === 2 ? [parts[0], parts[1], parts[0], parts[1]] : parts.length === 3 ? [parts[0], parts[1], parts[2], parts[1]] : parts
  const side = (name: 'left' | 'right' | 'top' | 'bottom', index: number): number => {
    const value = px(css(node, name, AFTER) ?? sides[index])
    return Number.isFinite(value) ? value : 0
  }
  const [a, b] = axis === 'x' ? [side('left', 3), side('right', 1)] : [side('top', 0), side('bottom', 2)]
  return (Number.isFinite(size) ? size : 0) - a - b
}

describe('PB-01·6 · a 24 px grab area on the Splitter', () => {
  test('[css] a vertical and a horizontal splitter: a 1 px line with a 24 px grab area across it', () => {
    render(<>
      <Splitter orientation="vertical" label="Sidebar width" value={280} min={200} max={480} defaultValue={280} onChange={() => {}} />
      <Splitter orientation="horizontal" label="Panel height" value={200} min={100} max={400} defaultValue={200} onChange={() => {}} />
    </>)
    const vertical = screen.getByRole('separator', { name: 'Sidebar width' })
    const horizontal = screen.getByRole('separator', { name: 'Panel height' })
    expect(px(css(vertical, ['width', 'inline-size'])), 'the line stays 1 px').toBe(1)
    expect(px(css(horizontal, ['height', 'block-size'])), 'the line stays 1 px').toBe(1)
    for (const [name, node, axis] of [['vertical', vertical, 'x'], ['horizontal', horizontal, 'y']] as const) {
      const area = grab(node, axis)
      expect(area, `${name} grab area ${area}px`).toBeGreaterThanOrEqual(px('var(--target-min)') - 1)
      expect(area, `${name} grab area ${area}px`).toBeLessThanOrEqual(25)
    }
  })

  test('[css] the edge splitter on a sidebar border also grabs 24 px across', () => {
    render(<Splitter edge orientation="vertical" label="Sidebar width" value={280} min={200} max={480} defaultValue={280} onChange={() => {}} />)
    const area = grab(screen.getByRole('separator', { name: 'Sidebar width' }), 'x')
    expect(area, `edge grab area ${area}px`).toBeGreaterThanOrEqual(px('var(--target-min)') - 1)
    expect(area, `edge grab area ${area}px`).toBeLessThanOrEqual(25)
  })
})
