import { describe, expect, it } from 'vitest'
import { checkExpression, checkType, maintenanceStatement, planStructure } from '../../electron/main/services/oxequery/ddl-builder'

const col = (name: string, type = 'text', extra: object = {}) => ({ name, type, nullable: true, ...extra })

describe('create table', () => {
  it('quotes every identifier and writes keys, indexes and comments', () => {
    const plan = planStructure('public', 'order items', {
      kind: 'create',
      table: {
        columns: [col('id', 'bigint', { nullable: false, identity: 'always' }), col('order id', 'int', { nullable: false }), col('price', 'numeric(10,2)', { default: '0', comment: "it's net" })],
        constraints: [{ kind: 'primary', columns: ['id'] }, { kind: 'foreign', columns: ['order id'], refSchema: 'public', refTable: 'orders', refColumns: ['id'], onDelete: 'cascade' }],
        indexes: [{ name: 'items_order', columns: ['order id'], method: 'hash' }],
        comment: 'lines'
      }
    })
    expect(plan.destructive).toBe(false)
    expect(plan.statements[0]).toContain('CREATE TABLE "public"."order items"')
    expect(plan.statements[0]).toContain('"id" bigint GENERATED ALWAYS AS IDENTITY NOT NULL')
    expect(plan.statements[0]).toContain('PRIMARY KEY ("id")')
    expect(plan.statements[0]).toContain('FOREIGN KEY ("order id") REFERENCES "public"."orders" ("id") ON DELETE CASCADE')
    expect(plan.statements).toContain('CREATE INDEX "items_order" ON "public"."order items" USING hash ("order id")')
    expect(plan.statements).toContain(`COMMENT ON COLUMN "public"."order items"."price" IS 'it''s net'`)
  })

  it('refuses duplicate columns, a table without columns and names PostgreSQL would cut', () => {
    expect(() => planStructure('public', 't', { kind: 'create', table: { columns: [col('a'), col('a')] } })).toThrow(/same name/)
    expect(() => planStructure('public', 't', { kind: 'create', table: { columns: [] } })).toThrow(/at least|between/)
    expect(() => planStructure('public', 'x'.repeat(64), { kind: 'create', table: { columns: [col('a')] } })).toThrow(/at most 63/)
  })
})

describe('alter table', () => {
  it('flags data loss and rewrites, and keeps the order of the changes', () => {
    const plan = planStructure('public', 'users', {
      kind: 'alter',
      changes: [
        { op: 'addColumn', column: col('age', 'int', { nullable: false }) },
        { op: 'alterColumn', name: 'email', type: 'varchar(200)', using: 'email::varchar' },
        { op: 'dropColumn', name: 'legacy' }
      ]
    })
    expect(plan.statements).toEqual([
      'ALTER TABLE "public"."users" ADD COLUMN "age" int NOT NULL',
      'ALTER TABLE "public"."users" ALTER COLUMN "email" TYPE varchar(200) USING email::varchar',
      'ALTER TABLE "public"."users" DROP COLUMN "legacy"'
    ])
    expect(plan.destructive).toBe(true)
    expect(plan.warnings.join(' ')).toMatch(/fails if the table has rows/)
  })

  it('writes defaults, nullability and identity changes separately', () => {
    const plan = planStructure('s', 't', { kind: 'alter', changes: [{ op: 'alterColumn', name: 'a', nullable: false, default: null, identity: 'by-default' }] })
    expect(plan.statements).toEqual([
      'ALTER TABLE "s"."t" ALTER COLUMN "a" SET NOT NULL',
      'ALTER TABLE "s"."t" ALTER COLUMN "a" DROP DEFAULT',
      'ALTER TABLE "s"."t" ALTER COLUMN "a" ADD GENERATED BY DEFAULT AS IDENTITY'
    ])
  })

  it('rejects an empty change set', () => {
    expect(() => planStructure('s', 't', { kind: 'alter', changes: [] })).toThrow()
    expect(() => planStructure('s', 't', { kind: 'alter', changes: [{ op: 'alterColumn', name: 'a' }] })).toThrow(/Nothing to change/)
  })
})

describe('drop, truncate, duplicate', () => {
  it('marks drop and truncate destructive', () => {
    expect(planStructure('s', 't', { kind: 'drop' })).toMatchObject({ statements: ['DROP TABLE "s"."t"'], destructive: true })
    expect(planStructure('s', 't', { kind: 'truncate', restartIdentity: true, cascade: true }).statements).toEqual(['TRUNCATE TABLE "s"."t" RESTART IDENTITY CASCADE'])
  })

  it('copies the structure, and the rows on request', () => {
    expect(planStructure('s', 't', { kind: 'duplicate', to: 't2' }).statements).toEqual(['CREATE TABLE "s"."t2" (LIKE "s"."t" INCLUDING ALL)'])
    expect(planStructure('s', 't', { kind: 'duplicate', to: 't2', withData: true }, ['a', 'b']).statements[1]).toBe('INSERT INTO "s"."t2" ("a", "b") OVERRIDING SYSTEM VALUE SELECT "a", "b" FROM "s"."t"')
  })
})

describe('what the page may not smuggle in', () => {
  it('only accepts type names', () => {
    expect(checkType('numeric(10,2)')).toBe('numeric(10,2)')
    expect(checkType('timestamp with time zone')).toBe('timestamp with time zone')
    expect(checkType('int[]')).toBe('int[]')
    for (const bad of ['int; DROP TABLE x', 'int)', 'text, b int', 'a--b', "int'", '']) expect(() => checkType(bad)).toThrow()
  })

  it('only accepts one expression without comments or outside calls', () => {
    expect(checkExpression("now() + interval '1 day'", 'x')).toBe("now() + interval '1 day'")
    expect(checkExpression("nextval('seq')", 'x')).toBe("nextval('seq')")
    expect(checkExpression("';' || 'a'", 'x')).toBe("';' || 'a'")
    for (const bad of ['1; DROP TABLE t', '1 -- c', '1 /* c */', '(1', "'open", 'pg_read_file(\'/etc/passwd\')', '']) expect(() => checkExpression(bad, 'x')).toThrow()
  })

  it('refuses a default carrying a second statement through a column', () => {
    expect(() => planStructure('s', 't', { kind: 'alter', changes: [{ op: 'addColumn', column: col('a', 'int', { default: '1); DROP TABLE t; --' }) }] })).toThrow()
  })
})

describe('maintenance', () => {
  it('maps each action to a single statement', () => {
    expect(maintenanceStatement('s', 't', 'vacuum-analyze')).toBe('VACUUM (ANALYZE) "s"."t"')
    expect(maintenanceStatement('s', 't', 'reindex')).toBe('REINDEX TABLE "s"."t"')
    expect(() => maintenanceStatement('s', 't', 'drop')).toThrow()
  })
})
