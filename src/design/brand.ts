import { LOGO } from './tokens/palette'

/**
 * The mandacaru mark's geometry (docs/design/brand.md), drawn on a 44-unit grid: one trunk and two arms, a task
 * that splits into agents. The logo, the brand loader and the boot splash draw from here so they never drift.
 */
export const MARK_VIEWBOX = '0 0 44 44'
export const MARK_STROKE = 4
export const MARK_TRUNK = 'M22 39V8'
export const MARK_ARM_LEFT = 'M22 27h-6a4 4 0 0 1-4-4v-7'
export const MARK_ARM_RIGHT = 'M22 21h6a4 4 0 0 0 4-4v-6'
/** Where each arm leaves the trunk: the loader grows the arms out of these points. */
export const MARK_ARM_LEFT_ORIGIN = '22px 27px'
export const MARK_ARM_RIGHT_ORIGIN = '22px 21px'
/** The sertão sun beside the cactus, without the tile. */
export const MARK_SUN = { cx: 10, cy: 8.5, r: 3.4 } as const

/** On the app icon the mark sits on a rounded tile, scaled to 80%, with a smaller sun. */
export const TILE_RADIUS = 11
export const MARK_ON_TILE = 'translate(4.4 4.4) scale(0.8)'
export const TILE_SUN = { cx: 12.4, cy: 11.2, r: 2.8 } as const

/**
 * The app icon as SVG, in the --logo-* colors. `npm run generate:icon` writes it to resources/icon.svg and renders
 * the PNG and ICO files from it; tests/brand-touchpoints.test.ts fails when the committed files drift from here.
 */
export function appIconSvg(): string {
  return [
    `<svg width="256" height="256" viewBox="${MARK_VIEWBOX}" xmlns="http://www.w3.org/2000/svg">`,
    '  <!-- OXESpace · Mandacaru (docs/design/brand.md). Generated by scripts/generate-icon.mjs from src/design/brand.ts. -->',
    `  <rect width="44" height="44" rx="${TILE_RADIUS}" fill="${LOGO.tile}"/>`,
    `  <g transform="${MARK_ON_TILE}" fill="none" stroke="${LOGO.mark}" stroke-width="${MARK_STROKE}" stroke-linecap="round" stroke-linejoin="round">`,
    ...[MARK_TRUNK, MARK_ARM_LEFT, MARK_ARM_RIGHT].map(d => `    <path d="${d}"/>`),
    '  </g>',
    `  <circle cx="${TILE_SUN.cx}" cy="${TILE_SUN.cy}" r="${TILE_SUN.r}" fill="${LOGO.sun}"/>`,
    '</svg>',
    ''
  ].join('\n')
}

/** The PNG sizes rendered for the desktop (Linux hicolor, macOS, installers): resources/icons/<size>x<size>.png. */
export const ICON_SIZES = [16, 24, 32, 48, 64, 128, 256, 512, 1024] as const
/** The sizes packed into resources/icon.ico for Windows. */
export const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256] as const
