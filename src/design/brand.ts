import { LOGO } from './tokens/palette'

/**
 * The Ramo mark's geometry (docs/design/brand.md): a mandacaru in five solid, round-ended columns on a 48-unit grid.
 * The trunk is 8 by 38; each arm is 8 wide and held to the trunk by a bridge; the right arm stands higher. A task that
 * splits into agents. The logo, the brand loader, the boot splash and the icon files draw from here so they never drift.
 */
export const MARK_VIEWBOX = '0 0 48 48'
/** Every column ends in a half circle: the radius is half the column width. */
export const MARK_RADIUS = 4

/** A round-ended column as a path, drawn clockwise so overlapping columns fill as one shape. */
function column(x: number, y: number, width: number, height: number): string {
  const r = MARK_RADIUS
  return width <= height
    ? `M${x + r} ${y}a${r} ${r} 0 0 1 ${r} ${r}v${height - 2 * r}a${r} ${r} 0 0 1 -${2 * r} 0v-${height - 2 * r}a${r} ${r} 0 0 1 ${r} -${r}z`
    : `M${x + r} ${y}h${width - 2 * r}a${r} ${r} 0 0 1 0 ${2 * r}h-${width - 2 * r}a${r} ${r} 0 0 1 0 -${2 * r}z`
}

export const MARK_TRUNK = column(20, 5, 8, 38)
/** Each arm with the bridge that holds it to the trunk. */
export const MARK_ARM_LEFT = column(8, 15, 8, 18) + column(8, 25, 16, 8)
export const MARK_ARM_RIGHT = column(32, 9, 8, 17) + column(24, 18, 16, 8)
/** The whole mark as one path: Android's vector drawables and anything else that takes a single path. */
export const MARK_PATH = MARK_TRUNK + MARK_ARM_LEFT + MARK_ARM_RIGHT
/** Where each bridge meets the trunk: the loader grows the arms out of these points. */
export const MARK_ARM_LEFT_ORIGIN = '24px 29px'
export const MARK_ARM_RIGHT_ORIGIN = '24px 22px'

/** On the app icon the mark sits on the night tile, scaled to 75% (one column of breathing room). */
export const TILE_RADIUS = 11
export const MARK_ON_TILE = 'translate(6 6) scale(0.75)'

/**
 * The app icon as SVG, in the --logo-* colors. `npm run generate:icon` writes it to resources/icon.svg and renders
 * the PNG and ICO files from it; tests/brand-touchpoints.test.ts fails when the committed files drift from here.
 */
export function appIconSvg(): string {
  return [
    `<svg width="256" height="256" viewBox="${MARK_VIEWBOX}" xmlns="http://www.w3.org/2000/svg">`,
    '  <!-- OXESpace · Ramo (docs/design/brand.md). Generated by scripts/generate-icon.mjs from src/design/brand.ts. -->',
    `  <rect width="48" height="48" rx="${TILE_RADIUS}" fill="${LOGO.tile}"/>`,
    `  <path transform="${MARK_ON_TILE}" fill="${LOGO.mark}" d="${MARK_PATH}"/>`,
    '</svg>',
    ''
  ].join('\n')
}

/** The PNG sizes rendered for the desktop (Linux hicolor, macOS, installers): resources/icons/<size>x<size>.png. */
export const ICON_SIZES = [16, 24, 32, 48, 64, 128, 256, 512, 1024] as const
/** The sizes packed into resources/icon.ico for Windows. */
export const ICO_SIZES = [16, 24, 32, 48, 64, 128, 256] as const
