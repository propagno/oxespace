/**
 * Renders the token CSS. `scripts/build-tokens.mjs` writes it to
 * `src/styles/tokens.generated.css`; a test fails when the file drifts from
 * this source, so edit the tokens here and rebuild.
 */
import { IDENTITY, LOGO, type Mode } from './palette'
import { colorRoles, elevations, surfaceColorRoles, type SurfaceStyle } from './semantic'
import { BAR, CHROME, CONTROL, FONT, LAYER, LEADING, MOTION, RADIUS, REDUCED_MOTION, ROW, SPACE, STRETCH, TARGET_MIN, TEXT, WEIGHT } from './scales'

/**
 * OXE-137 (T18): the CSS carries the short canonical names of the type sizes (--fs-*), text colors (--tx-*) and borders
 * (--bd-*). The keys of scales.ts and semantic.ts keep their long names, since the phone's Kotlin (OxeTokens.kt) reads them.
 */
const SHORT_NAMES: ReadonlyArray<readonly [long: string, short: string, suffixes: readonly string[]]> = [
  ['text', 'fs', ['2xs', 'xs', 'sm', 'md', 'lg', 'xl', 'display']],
  ['text', 'tx', ['primary', 'secondary', 'muted', 'disabled', 'on-accent', 'on-solid', 'on-identity', 'accent', 'link']],
  ['border', 'bd', ['default', 'subtle', 'strong', 'control', 'focus']]
]
const CSS_NAME = new Map<string, string>(SHORT_NAMES.flatMap(([long, short, suffixes]) => suffixes.map(suffix => [`${long}-${suffix}`, `${short}-${suffix}`])))
const cssName = (name: string): string => CSS_NAME.get(name) ?? name

const block = (selector: string, entries: Record<string, string | number>, extra: string[] = []): string =>
  `${selector} {\n${[...Object.entries(entries).map(([name, value]) => `  --${cssName(name)}: ${value};`),...extra.map(line => `  ${line}`)].join('\n')}\n}`

function modeTokens(mode: Mode, surface: SurfaceStyle = 'default'): Record<string, string> {
  return { ...surfaceColorRoles(mode, surface), ...elevations(mode, surface) }
}

/**
 * More contrast (the operating system's "increase contrast", prefers-contrast: more): every border takes the strong
 * step and muted text reads as secondary, so edges and quiet labels stand out. Forced colors (Windows high contrast)
 * is a separate stylesheet, src/styles/forced-colors.css.
 */
export function moreContrastTokens(mode: Mode, surface: SurfaceStyle = 'default'): Record<string, string> {
  const roles = colorRoles(mode, surface)
  return {
    'border-subtle': roles['border-strong'], 'border-default': roles['border-strong'],
    'text-muted': roles['text-secondary'], 'text-disabled': roles['text-muted']
  }
}

function staticTokens(): Record<string, string | number> {
  const out: Record<string, string | number> = {
    'font-display': FONT.display, 'font-ui': FONT.ui, 'font-mono': FONT.mono,
    'stretch-display': STRETCH.display, 'stretch-title': STRETCH.title
  }
  for (const [name, value] of Object.entries(SPACE)) out[`space-${name}`] = value
  for (const [name, value] of Object.entries(TEXT)) out[`text-${name}`] = `${value}px`
  for (const [name, value] of Object.entries(WEIGHT)) out[`weight-${name}`] = value
  for (const [name, value] of Object.entries(LEADING)) out[`leading-${name}`] = value
  for (const [name, value] of Object.entries(RADIUS)) out[`radius-${name}`] = value
  for (const [name, value] of Object.entries(CONTROL.compact)) out[`control-${name}`] = `${value}px`
  for (const [name, value] of Object.entries(BAR.compact)) out[`bar-${name}`] = `${value}px`
  for (const [name, value] of Object.entries(ROW.compact)) out[`row-${name}`] = `${value}px`
  out['target-min'] = `${TARGET_MIN}px`
  for (const [name, value] of Object.entries(LAYER)) out[`layer-${name}`] = value
  for (const [name, value] of Object.entries(CHROME)) out[name] = value
  for (const [name, value] of Object.entries(MOTION)) out[name] = value
  for (const [name, value] of Object.entries(LOGO)) out[`logo-${name}`] = value
  for (const [name, value] of Object.entries(IDENTITY.provider)) out[`provider-${name}`] = value
  IDENTITY.avatar.forEach((value, index) => { out[`avatar-${index + 1}`] = value })
  return out
}

export function tokensCss(): string {
  const comfortable: Record<string, string> = {}
  for (const [name, value] of Object.entries(TEXT)) if (name !== 'xl' && name !== 'display') comfortable[`text-${name}`] = `${value + 1}px`
  for (const [name, value] of Object.entries(CONTROL.comfortable)) comfortable[`control-${name}`] = `${value}px`
  for (const [name, value] of Object.entries(BAR.comfortable)) comfortable[`bar-${name}`] = `${value}px`
  for (const [name, value] of Object.entries(ROW.comfortable)) comfortable[`row-${name}`] = `${value}px`
  return [
    '/* Generated by scripts/build-tokens.mjs from src/design/tokens. Do not edit. */',
    block(':root', staticTokens()),
    // A subtree can force a mode with data-mode (previews, the design-system viewer).
    block(":root, [data-mode='light']", modeTokens('light'), ['color-scheme: light;']),
    block(":root[data-mode='dark'], [data-mode='dark']", modeTokens('dark'), ['color-scheme: dark;']),
    // Before the first script sets data-mode (the boot splash), the operating system's choice decides, as System would.
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-mode])', modeTokens('dark'), ['color-scheme: dark;']).replace(/^/gm, '  ')}\n}`,
    // Obsidian Minimal pure surface presets: Light White and True Black (OLED).
    block(":root[data-mode='light'][data-surface='pure'], [data-mode='light'][data-surface='pure']", modeTokens('light', 'pure'), ['color-scheme: light;']),
    block(":root[data-mode='dark'][data-surface='pure'], [data-mode='dark'][data-surface='pure']", modeTokens('dark', 'pure'), ['color-scheme: dark;']),
    block(":root[data-density='comfortable']", comfortable),
    `@media (prefers-contrast: more) {\n${[
      block(":root, [data-mode='light']", moreContrastTokens('light')),
      block(":root[data-mode='dark'], [data-mode='dark']", moreContrastTokens('dark')),
      block(":root[data-mode='light'][data-surface='pure'], [data-mode='light'][data-surface='pure']", moreContrastTokens('light', 'pure')),
      block(":root[data-mode='dark'][data-surface='pure'], [data-mode='dark'][data-surface='pure']", moreContrastTokens('dark', 'pure'))
    ].join('\n').replace(/^/gm, '  ')}\n}`,
    // Motion collapses for people who ask for less of it: Settings › Appearance sets data-motion on the
    // root (System resolves the operating system's choice); before that attribute exists, the media query decides.
    block(":root[data-motion='reduce']", REDUCED_MOTION),
    `@media (prefers-reduced-motion: reduce) {\n${block(':root:not([data-motion])', REDUCED_MOTION).replace(/^/gm, '  ')}\n}`,
    ''
  ].join('\n\n')
}
