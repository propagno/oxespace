package com.oxespace.mobile.protocol.pairing

import com.oxespace.mobile.protocol.RemoteAckFrame
import com.oxespace.mobile.protocol.RemoteAuthFrame
import com.oxespace.mobile.protocol.RemoteHelloFrame
import com.oxespace.mobile.protocol.session.SessionProtocol
import com.oxespace.mobile.protocol.session.TokenHolder
import java.security.KeyPairGenerator
import java.security.Signature
import java.security.spec.ECGenParameterSpec
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Frozen acceptance test for 1.5.2 Celular A16 (OXE program oxespace-152-mobile, phase F4, Jira OXE-179 CA-1 to CA-3:
 * the paired computer's details and the pairing code's expiry through the protocol, an additive C5 change). Written by
 * the planner; the executor must not edit it.
 *
 * The phone side of the contract (the desktop side is tests/oxe152/mobile/oxe179-pairing-details.native.test.ts):
 * - the QR's optional `exp` (RemotePairingQr.exp, epoch ms on the desktop's clock when the one-time code expires) is
 *   read into `PairingQr.expiresAt: Long?` (null when the QR has none, as an older desktop's); a malformed `exp`
 *   refuses the code as MALFORMED, as `readPairingUri` does;
 * - the sign-in result's optional `desktopOs` and `pairedAt` (RemoteAuthResult, generated by npm run android:generate)
 *   reach the session: `SessionState.Ready(desktopName, desktopOs: String? = null, pairedAt: Long? = null)`;
 * - an older phone (the 1.4.3 classes kept in compat/v143) reads the new sign-in result: the guard below.
 * New fields are read through the data classes' toString, so this file compiles on main before they exist.
 *
 * Red at F4 @ origin/main 4fabc30f5: PairingQr has no expiresAt (an `exp` is ignored, a malformed one accepted) and
 * Ready carries only the desktop's name.
 */
class PairingDetailsProtocolTest {
    private val fp = "b".repeat(64)
    private val base = "oxespace://pair?v=1&host=192.168.0.12&port=7443&fp=$fp&code=AbCdEfGhIjKlMnOpQrSt_-&name=Studio"

    private fun read(uri: String): PairingQrRead = PairingQrs.read(uri)

    @Test
    fun theQrCarriesTheCodesExpiry() {
        val read = read("$base&exp=1700000120000")
        assertTrue("a QR with exp reads: $read", read is PairingQrRead.Ok)
        val qr = (read as PairingQrRead.Ok).qr
        assertTrue("PairingQr.expiresAt is the QR's exp: $qr", qr.toString().contains("expiresAt=1700000120000"))
    }

    @Test
    fun aQrWithoutExpiryStillReadsWithNone() {
        val read = read(base)
        assertTrue("an older desktop's QR (no exp) reads: $read", read is PairingQrRead.Ok)
        assertTrue("with no expiry: ${(read as PairingQrRead.Ok).qr}", read.qr.toString().contains("expiresAt=null"))
    }

    @Test
    fun aMalformedExpiryRefusesTheCode() {
        for (bad in listOf("abc", "-5", "1.5", "")) {
            assertEquals("exp=$bad", PairingQrRead.Refused(PairingQrProblem.MALFORMED), read("$base&exp=$bad"))
        }
    }

    @Test
    fun theSignInCarriesTheComputersOsAndThePairingDate() {
        val keyPair = KeyPairGenerator.getInstance("EC").apply { initialize(ECGenParameterSpec("secp256r1")) }.generateKeyPair()
        var ids = 0
        fun session() = SessionProtocol(
            deviceId = "dev-1",
            fingerprint = fp,
            sign = { data -> Signature.getInstance("SHA256withECDSA").run { initSign(keyPair.private); update(data); sign() } },
            tokens = TokenHolder(),
            now = { 1_000_000L },
            newId = { "id-${++ids}" },
        )
        val challenge = "A".repeat(43)

        val withDetails = session()
        withDetails.onOpen()
        val auth = withDetails.onFrame(RemoteHelloFrame(versions = listOf(1L), desktopName = "Studio", challenge = challenge)).single() as RemoteAuthFrame
        withDetails.onFrame(
            RemoteAckFrame(
                id = auth.id,
                result = buildJsonObject {
                    put("accessToken", "tok-1")
                    put("expiresInMs", 900_000)
                    put("desktopOs", "Windows 11")
                    put("pairedAt", 1_699_000_000_000)
                },
            ),
        )
        val ready = withDetails.state.toString()
        assertTrue("Ready carries the OS: $ready", ready.startsWith("Ready(") && ready.contains("desktopOs=Windows 11"))
        assertTrue("Ready carries the pairing date: $ready", ready.contains("pairedAt=1699000000000"))

        val older = session()
        older.onOpen()
        val auth2 = older.onFrame(RemoteHelloFrame(versions = listOf(1L), desktopName = "Studio", challenge = challenge)).single() as RemoteAuthFrame
        older.onFrame(RemoteAckFrame(id = auth2.id, result = buildJsonObject { put("accessToken", "tok-2"); put("expiresInMs", 900_000) }))
        val plain = older.state.toString()
        assertTrue("an older desktop (no details) still signs in, with none: $plain", plain.startsWith("Ready(") && plain.contains("desktopOs=null") && plain.contains("pairedAt=null"))
    }
}

/** Guard of A16, green on main: an older phone (the 1.4.3 classes) reads the new sign-in result. Frozen with the test above. */
class PairingDetailsCompatGuardTest {
    @Test
    fun anOlderPhoneReadsTheNewSignInResult() {
        val text = """{"accessToken":"tok-1","expiresInMs":900000,"desktopOs":"Windows 11","pairedAt":1699000000000}"""
        val old = com.oxespace.mobile.compat.v143.RemoteFrames.json.decodeFromString(com.oxespace.mobile.compat.v143.RemoteAuthResult.serializer(), text)
        assertEquals("tok-1", old.accessToken)
        assertEquals(900_000L, old.expiresInMs)
    }
}
