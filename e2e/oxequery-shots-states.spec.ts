import { _electron as electron, expect, test, type Page } from '@playwright/test'
import { mkdirSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { connectFromContainer, openView } from './helpers/oxepod'

/** Screenshots of the states the first sweep misses (errors, plans, menus, dialogs, empty views) in both modes. */
const OUT = join(process.cwd(), 'e2e/screenshots/oxequery-states' + (process.env.SHOTS_W ? '-' + process.env.SHOTS_W : ''))

async function mode(page: Page, value: 'light' | 'dark'): Promise<void> {
  await page.evaluate(next => { document.documentElement.dataset.mode = next }, value)
  await page.waitForTimeout(250)
}

test('captures the OxeQuery states', async () => {
  test.setTimeout(300_000)
  mkdirSync(OUT, { recursive: true })
  const root = mkdtempSync(join(tmpdir(), 'oxespace-oxequery-states-'))
  const repo = join(root, 'repo'); mkdirSync(repo)
  const app = await electron.launch({ args: [join(process.cwd(), 'e2e/electron-main.cjs')], env: {
    ...process.env, OXESPACE_DISABLE_SINGLE_INSTANCE: '1', OXESPACE_E2E_MOCK_NATIVE: '1', OXESPACE_DB_PATH: join(root, 'app.sqlite3')
  } })
  try {
    const page = await app.firstWindow()
    await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows()[0].setSize(Number(process.env.SHOTS_W ?? 1360), Number(process.env.SHOTS_H ?? 860)) })
    await page.waitForLoadState('domcontentloaded')
    await page.getByTestId('btn-new-workspace').click()
    await page.getByTestId('wizard-dir-input').fill(repo)
    await page.getByTestId('wizard-layout-card-1').click()
    await page.getByTestId('wizard-launch-btn').click()
    await page.getByRole('navigation', { name: 'Application view' }).getByRole('button', { name: 'OxeQuery' }).click()
    await page.waitForTimeout(600)
    const shot = async (name: string): Promise<void> => { for (const m of ['light', 'dark'] as const) { await mode(page, m); await page.screenshot({ path: join(OUT, `${name}-${m}.png`) }) } }

    // OxePod: resources and container details.
    await openView(page, 'OxePod')
    await page.getByRole('button', { name: 'Images, volumes and networks' }).last().click()
    await page.waitForTimeout(500)
    await shot('01-resources')
    await page.getByRole('button', { name: /mongo-dev/ }).first().click()
    await page.waitForTimeout(400)
    await shot('02-container-details')
    await openView(page, 'OxeQuery')

    // OxeQuery: wizard, connection form, activity.
    await page.getByRole('button', { name: 'New local database' }).click()
    await page.getByRole('dialog', { name: 'New database' }).waitFor()
    await shot('03-new-database')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'New connection' }).first().click()
    await page.getByRole('dialog', { name: 'New connection' }).waitFor()
    await shot('04-new-connection-postgres')
    await page.getByRole('dialog').getByRole('radio', { name: /MongoDB/ }).click()
    await shot('05-new-connection-mongo-url')
    await page.getByRole('dialog').getByRole('button', { name: /Security/ }).click()
    await page.getByRole('dialog').getByRole('button', { name: /SSH tunnel/ }).click()
    await shot('06-connection-sections-open')
    await page.keyboard.press('Escape')
    await page.locator('.oq-sidebar').getByRole('button', { name: 'Agent activity' }).click()
    await shot('07-activity-empty')

    // SQL: error, plan, ask menu, filter, params, transaction.
    await connectFromContainer(page, 'pg-dev')
    await page.getByRole('button', { name: 'Edit pg-dev' }).click()
    const dialog = page.getByRole('dialog', { name: 'Edit connection' })
    await dialog.getByRole('switch', { name: /Read-only/ }).setChecked(false)
    await dialog.getByRole('button', { name: 'Save' }).click()
    const editor = page.locator('.oq-editor .monaco-editor')
    const type = async (text: string): Promise<void> => { await editor.click(); await page.keyboard.press('Control+A'); await page.keyboard.insertText(text); await page.keyboard.press('Escape') }
    await type('SELEC broken')
    await page.getByRole('button', { name: /^Run/ }).first().click()
    await page.waitForTimeout(700)
    await shot('10-sql-error')
    await type('SELECT * FROM users ORDER BY id')
    await page.getByRole('button', { name: 'Explain', exact: true }).click()
    await page.getByRole('region', { name: 'Execution plan' }).waitFor()
    await shot('11-sql-plan')
    await page.getByRole('button', { name: 'Close plan' }).click()
    await page.getByRole('button', { name: 'Ask agent' }).click()
    await page.getByRole('menu', { name: 'Ask agent' }).waitFor()
    await shot('12-ask-agent-menu')
    await page.keyboard.press('Escape')
    await type('SELECT :name AS n')
    await page.getByRole('button', { name: /^Run/ }).first().click()
    await page.waitForTimeout(500)
    await shot('13-sql-parameters')
    await page.keyboard.press('Escape')
    await type('SELECT 1; SELECT 2;')
    await page.keyboard.press('Control+Shift+Enter')
    await page.waitForTimeout(700)
    await shot('14-sql-multi-results')
    await page.getByRole('button', { name: 'Begin transaction' }).click()
    await page.waitForTimeout(400)
    await shot('15-sql-transaction')
    await page.getByRole('button', { name: 'Roll back' }).click()
    await page.getByRole('treeitem', { name: 'users', exact: true }).click({ position: { x: 12, y: 8 } })
    await expect(page.getByRole('gridcell', { name: 'alice', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Filter' }).click()
    await page.waitForTimeout(300)
    await shot('16-sql-filter')
    await page.getByRole('button', { name: 'Edit rows' }).click()
    await page.getByRole('gridcell', { name: 'alice', exact: true }).dblclick()
    await page.keyboard.press('Control+A'); await page.keyboard.type('alicia'); await page.keyboard.press('Enter')
    await page.waitForTimeout(400)
    await shot('17-sql-row-edit')
    await page.getByRole('button', { name: 'Import', exact: true }).click()
    await page.getByRole('dialog', { name: /Import into/ }).waitFor()
    await page.waitForTimeout(400)
    await shot('17b-import-dialog')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'New table' }).click()
    await page.getByRole('dialog', { name: /New table/ }).waitFor()
    await shot('17c-new-table')
    await page.keyboard.press('Escape')

    // Server roles and settings.
    await page.getByRole('button', { name: 'Server: databases and roles' }).click()
    await page.getByRole('dialog', { name: /Server of/ }).waitFor()
    await page.getByRole('tab', { name: 'Roles' }).waitFor(); await page.waitForTimeout(500); await page.getByRole('tab', { name: 'Roles' }).click()
    await page.waitForTimeout(400)
    await shot('18-server-roles')
    await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'OxeQuery settings' }).click()
    await page.getByRole('dialog', { name: 'OxeQuery settings' }).waitFor()
    await page.waitForTimeout(500)
    await shot('19-settings')
    await page.keyboard.press('Escape')

    // Mongo: aggregate, edit document, many-change dialog.
    await connectFromContainer(page, 'mongo-dev')
    const sidebar = page.getByRole('navigation', { name: 'Databases' })
    await sidebar.getByRole('button', { name: 'shop', exact: true }).click()
    await sidebar.getByRole('button', { name: 'items', exact: true }).click()
    await expect(page.getByText('_id: 507f1f77bcf86cd799439011')).toBeVisible()
    await page.getByRole('radio', { name: 'Table' }).click()
    await shot('20-mongo-table')
    await page.getByRole('radio', { name: 'Documents' }).click()
    await page.getByRole('button', { name: 'Aggregate' }).click()
    await page.waitForTimeout(400)
    await shot('21-mongo-aggregate')
  } finally { await app.close() }
})
